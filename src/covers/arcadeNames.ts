/** Título completo de un romset arcade (por nombre de archivo), o null si no se conoce. */
export function arcadeTitle(path: string): string | null {
  const base = (path.split('/').pop() ?? path).replace(/\.zip$/i, '').toLowerCase();
  return ARCADE_TITLES[base] ?? null;
}
